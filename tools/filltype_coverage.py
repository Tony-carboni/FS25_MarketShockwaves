#!/usr/bin/env python3
"""
Fill-type coverage export.

Cross-references the game's fill types against config/events.xml and reports
which products the mod can work with, and which events (if any) touch each one.

"Workable" means showOnPriceTable="true": those are the products whose sell price
our EconomyAdapter hook can move. Everything else is listed separately with the
reason it is out of reach.

Usage:
    python3 tools/filltype_coverage.py                 # print
    python3 tools/filltype_coverage.py -o FILE         # write to FILE
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILLTYPES = ROOT / "reference/fillTypes_basegame.xml"
EVENTS = ROOT / "FS25_MarketShockwaves/config/events.xml"

# Products left out ON PURPOSE, so the "unused" list is not read as a to-do.
# Without this, the report invites someone to wire back exactly what was
# deliberately removed.
DELIBERATE = {
    "RICESAPLINGS": "planting stock; volumes too small for the player to feel "
                    "a price change (see DESIGN.md)",
    "ROADSALT": "pricePerLiter is 0, so a multiplier can never move it",
    "FORAGE": "no pricePerLiter at all; mixed on-farm, not traded",
    "SUGARBEET_CUT": "harvest intermediate, not a traded good",
    "STONE": "field-clearing by-product, near-worthless",
}

# Products that exist but are not price-table products, with why.
UNREACHABLE_NOTES = {
    "livestock": "animal dealer system, not the price table (see DESIGN.md)",
    "state": "field/crop state, never traded",
    "internal": "internal or engine-only fill type",
}


def load_filltypes():
    """Return [(name, pricePerLiter, onPriceTable)] in file order."""
    text = FILLTYPES.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'<fillType name="([^"]+)"(.*?)</fillType>', text, re.S):
        name, block = m.group(1), m.group(0)
        price = re.search(r'pricePerLiter="([\d.]+)"', block)
        show = re.search(r'showOnPriceTable="(true|false)"', block)
        out.append((
            name,
            float(price.group(1)) if price else None,
            (show.group(1) == "true") if show else False,
        ))
    return out


def load_events():
    """Return (direct, ripple) dicts: product -> [event annotations]."""
    root = ET.parse(EVENTS).getroot()
    direct, ripple = {}, {}
    for ev in root.find("events").findall("event"):
        eid = ev.get("id")
        etype = ev.get("type")
        tag = f"{eid}({etype[0]})"      # e.g. grainDrought(w)

        affects = ev.find("affects")
        if affects is not None and affects.text:
            for p in affects.text.split():
                direct.setdefault(p, []).append(tag)

        chains = ev.find("chains")
        if chains is not None:
            for ch in chains.findall("chain"):
                to = ch.get("to")
                tier = ch.get("tier", "1")
                pt = ch.get("passThrough")
                note = f"{eid} t{tier}"
                if pt:
                    note += f" x{pt}"
                ripple.setdefault(to, []).append(note)
    return direct, ripple


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if --output is missing or out of date, without "
                         "writing it (for CI)")
    args = ap.parse_args()

    # The public repository ships no GIANTS game data. Without it this report
    # cannot be produced at all, so skip rather than fail: the committed copy of
    # docs/filltype-coverage.txt remains the reference, and anyone with a game
    # install can regenerate it.
    if not FILLTYPES.exists():
        print("NOTE  reference/fillTypes_basegame.xml not present — cannot "
              "generate the coverage report.")
        print("      Copy fillTypes.xml from your Farming Simulator 25 install "
              "(data/maps/maps_fillTypes.xml)")
        print("      to that path to enable it. It is deliberately not "
              "redistributed.")
        return 0

    filltypes = load_filltypes()
    direct, ripple = load_events()

    workable = [(n, p) for n, p, ok in filltypes if ok]
    blocked = [(n, p) for n, p, ok in filltypes if not ok]

    L = []
    add = L.append

    add("=" * 78)
    add("FS25 MARKET SHOCKWAVES - FILL TYPE COVERAGE")
    add("=" * 78)
    add("")
    add("Generated by tools/filltype_coverage.py from:")
    add("  reference/fillTypes_basegame.xml   (the game's own fill type data)")
    add("  FS25_MarketShockwaves/config/events.xml")
    add("")
    add("WORKABLE = showOnPriceTable=\"true\". Those are the products whose sell")
    add("price our EconomyAdapter hook can move. Prices are pricePerLiter;")
    add("multiply by 1000 for the in-game per-1000L display.")
    add("")
    add("Event tags:  (w)=win  (l)=lose  (n)=neutral")
    add("  direct  = listed in the event's <affects>, moves at FULL magnitude")
    add("  ripple  = reached through a chain; tN = tier, xN = pass-through")
    add("")
    add(f"TOTALS: {len(workable)} workable, "
        f"{sum(1 for n, _ in workable if n in direct or n in ripple)} covered by "
        f"at least one event, "
        f"{sum(1 for n, _ in workable if n not in direct and n not in ripple)} unused")
    add("")

    # ---------------- covered ----------------
    add("-" * 78)
    add("WORKABLE AND IN USE")
    add("-" * 78)
    for name, price in workable:
        if name not in direct and name not in ripple:
            continue
        parts = []
        if name in direct:
            parts.append("direct: " + ", ".join(direct[name]))
        if name in ripple:
            parts.append("ripple: " + ", ".join(ripple[name]))
        pr = f"{price:.3f}" if price is not None else "-"
        add(f"{name:<22}{pr:>8}   {'  |  '.join(parts)}")
    add("")

    # ---------------- unused ----------------
    add("-" * 78)
    add("WORKABLE BUT NOT IN ANY EVENT")
    add("-" * 78)
    add("Available to build events around - EXCEPT those marked DELIBERATE,")
    add("which were considered and left out. Do not wire those back without")
    add("reading the reason.")
    add("")
    for name, price in workable:
        if name in direct or name in ripple:
            continue
        pr = f"{price:.3f}" if price is not None else "-"
        why = DELIBERATE.get(name)
        note = f"   DELIBERATE: {why}" if why else ""
        add(f"{name:<22}{pr:>8}{note}")
    add("")

    # ---------------- unreachable ----------------
    add("-" * 78)
    add("NOT WORKABLE - showOnPriceTable=\"false\"")
    add("-" * 78)
    add("These cannot be moved by the fill-type price hook.")
    add("")
    for name, price in blocked:
        why = ""
        if re.match(r"^(COW|PIG|SHEEP|HORSE|CHICKEN|GOAT)", name):
            why = "  <- " + UNREACHABLE_NOTES["livestock"]
        elif name in ("GRASS", "MEADOW", "DRYGRASS", "WEED", "TREE", "POPLAR",
                      "OILSEEDRADISH", "TREESAPLINGS"):
            why = "  <- " + UNREACHABLE_NOTES["state"]
        pr = f"{price:.3f}" if price is not None else "-"
        add(f"{name:<22}{pr:>8}{why}")
    add("")

    # ---------------- per-event summary ----------------
    add("-" * 78)
    add("PRODUCTS PER EVENT")
    add("-" * 78)
    add("")
    root = ET.parse(EVENTS).getroot()
    for ev in root.find("events").findall("event"):
        eid, etype = ev.get("id"), ev.get("type")
        aff = (ev.find("affects").text or "").split() if ev.find("affects") is not None else []
        chains = ev.find("chains")
        tos = [c.get("to") for c in chains.findall("chain")] if chains is not None else []
        add(f"{eid}  [{etype}]  {len(aff)} direct + {len(tos)} ripple = {len(aff)+len(tos)} products")
        if aff:
            add(f"    direct: {' '.join(aff)}")
        if tos:
            add(f"    ripple: {' '.join(tos)}")
        add("")

    text = "\n".join(L) + "\n"
    if args.check:
        if not args.output:
            print("--check needs --output"); return 2
        target = Path(args.output)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != text:
            print(f"STALE {args.output} — regenerate with "
                  f"python3 tools/filltype_coverage.py -o {args.output}")
            return 1
        print(f"{args.output} is up to date")
        return 0
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"wrote {args.output} ({len(L)} lines)")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
